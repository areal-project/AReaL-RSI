"""Platform-neutral environment evaluation client contract."""

from __future__ import annotations

from typing import Protocol

from areal_rsi.schemas.core import EvalJob, EvalRequest, Traj


class EnvClient(Protocol):
    """Minimal environment interface required by the RSI controller."""

    def submit_eval(self, request: EvalRequest) -> EvalJob:
        """Submit an evaluation run."""

    def get_eval_progress(self, job: EvalJob) -> dict[str, object]:
        """Return the current status and progress for an evaluation run."""

    def get_eval_result(self, job: EvalJob) -> dict[str, object]:
        """Return the aggregated result for a completed evaluation run."""

    def get_trajs(self, job: EvalJob, include_messages: bool = False) -> list[Traj]:
        """Fetch trajectories generated by an evaluation run."""
